export function getEntityBySlug(slug: string) {
  return entities.find((e) => e.slug === slug);
}

export function getEntityById(id: string) {
  return entities.find((e) => e.id === id);
}

export function getEntitiesByWriter(writerId: string) {
  return entities.filter((e) => e.writerIds.includes(writerId));
}

export function getEntitiesByIds(ids: string[]) {
  return ids
    .map((id) => getEntityById(id))
    .filter((e): e is Entity => Boolean(e));
}
